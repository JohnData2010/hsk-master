/**
 * Get intelligent mnemonic and reading tip for any word
 */
export const getLearningTipForWord = (word) => {
  if (!word) return null;
  const hanzi = word.hanzi || '';

  // 1. Exact match in character dictionary
  if (CHARACTER_MNEMONICS[hanzi]) {
    return CHARACTER_MNEMONICS[hanzi];
  }

  // 2. Multi-char word: try matching first or second char
  for (let char of hanzi) {
    if (CHARACTER_MNEMONICS[char]) {
      return {
        breakdown: `Chữ trọng tâm "${char}": ${CHARACTER_MNEMONICS[char].breakdown}`,
        story: CHARACTER_MNEMONICS[char].story,
        tip: `Âm Hán - Việt là "${word.han_viet}". Khi nhớ nghĩa Hán Việt, bạn sẽ hiểu ngay vì tiếng Việt có đến 70% từ gốc Hán tương đồng!`
      };
    }
  }

  // 3. Fallback cognitive mnemonic based on Sino-Vietnamese cognate connection
  return {
    breakdown: `Từ ghép Hán tự: ${hanzi.split('').join(' + ')}`,
    story: `Ghi nhớ qua âm Hán - Việt: "${word.han_viet}". Từ "${word.vietnamese}" trong tiếng Việt mượn gốc từ chữ này!`,
    tip: `Phát âm Pinyin "${word.pinyin}": Hãy chú ý thanh điệu rõ ràng, không nuốt âm.`
  };
};
